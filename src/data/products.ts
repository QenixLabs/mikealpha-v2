export function getProductBySlug(slug: string): Product | undefined {
  const direct = products.find((p) => p.slug === slug)
  if (direct) return direct
  // Backward-compatibility aliases
  if (slug === "root-x") return products.find((p) => p.slug === "root-x-4kg")
  if (slug === "mike-cote-pro" || slug === "mike-cote-nursery") return products.find((p) => p.slug === "maxima-15-5-5")
  if (slug === "00-60-20") return products.find((p) => p.slug === "kaliphos")
  if (slug === "13-00-45") return products.find((p) => p.slug === "00-00-50")
  if (slug === "bacs") return products.find((p) => p.slug === "nema")
  return undefined
}

export function getRelatedProducts(product: Product): Product[] {
  if (!product.relatedSlugs) return []
  return product.relatedSlugs.map((slug) => getProductBySlug(slug)).filter(Boolean) as Product[]
}
